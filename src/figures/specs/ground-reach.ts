/** The ground figures of the spec sets given, those in the table with their published length set. */
export function groundReach(sets: SpecSet[]): SpecSet {
  const last: Named<GroundSpec> = {};
  for (const s of sets) Object.assign(last, s.ground ?? {});
  const ground: Named<GroundSpec> = {};
  for (const [name, overall] of Object.entries(OVERALL)) if (last[name]) ground[name] = { ...last[name], overall };
  return { ground };
}

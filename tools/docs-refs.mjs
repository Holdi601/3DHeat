/**
 * Writes the documentation's reference pages from the code, so they cannot
 * drift from it: event types and classes, the column names the loader
 * recognises, the languages, the browser keys the viewer keeps, the settings
 * kept in the browser, the value tables and the command-line tools.
 *
 *   node tools/docs-refs.mjs [--lang en] [--check]
 *
 * Labels (event and class names) come from the language's locale files, so
 * each language's pages name things as its UI does. Pages go to docs/ for
 * English and docs/<lang>/ otherwise. --check writes nothing and exits 1 when
 * a page would change (for a release check or CI).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const LANG = arg('lang', 'en');
const CHECK = process.argv.includes('--check');
const REPO = resolve(import.meta.dirname, '..');
const OUT = LANG === 'en' ? join(REPO, 'docs') : join(REPO, 'docs', LANG);
const src = (p) => readFileSync(join(REPO, p), 'utf8');

const strings = {};
for (const lang of ['en', LANG]) {
  const dir = join(REPO, 'src', 'i18n', 'locales', lang);
  for (const f of readdirSync(dir)) if (f.endsWith('.json')) Object.assign(strings, JSON.parse(readFileSync(join(dir, f), 'utf8')));
}
const L = (key, fallback) => strings[key] ?? fallback ?? key;
const cell = (s) => String(s).replace(/\|/g, '\\|');
const page = (title, order, body) =>
  `---\ntitle: ${title}\nparent: Reference\nnav_order: ${order}\n---\n\n<!-- Generated by tools/docs-refs.mjs from the code. Do not edit by hand. -->\n\n# ${title}\n\n${body.trim()}\n`;

const pages = {};

// ------------------------------------------------------------ event types and classes
{
  const canon = src('src/data/canonical.ts');
  const list = (name) => JSON.parse(canon.match(new RegExp(`export const ${name} = (\\[[^\\]]*\\])`))[1].replace(/'/g, '"'));
  const kinds = list('EVENT_KINDS');
  const classes = list('VEHICLE_CLASSES');
  const mapText = canon.slice(canon.indexOf('const EVENT_MAP'), canon.indexOf('};', canon.indexOf('const EVENT_MAP')));
  const words = {};
  for (const m of mapText.matchAll(/(?:'([^']*)'|([A-Za-z_][\w]*))\s*:\s*'(\w+)'/g)) {
    const word = m[1] ?? m[2];
    (words[m[3]] ??= []).push(word === '' ? '(empty)' : word);
  }
  let body = 'The viewer adds an **Event type** column to every dataset that has an event column (`event`, `events`, `event_type` or `event_name`). Each game\'s own words are mapped to one of these kinds (upper and lower case alike); a word not listed counts as *Other*.\n\n| Kind | Shown as | Words in the data |\n|---|---|---|\n';
  for (const k of kinds) body += `| \`${k}\` | ${cell(L(`heat.filterPanel.event.${k}`, k))} | ${(words[k] ?? []).map((w) => `\`${cell(w)}\``).join(', ')} |\n`;
  body += '\n## Vehicle classes\n\nThe **Vehicle class** and **Target class** columns use these classes, worked out from vehicle names (through the [figure catalogue](figures.md)) and type columns.\n\n| Class | Shown as |\n|---|---|\n';
  for (const c of classes) body += `| \`${c}\` | ${cell(L(`heat.filterPanel.vehicleClass.${c}`, c))} |\n`;
  pages['ref-event-types.md'] = page('Event types and classes', 1, body);
}

// ------------------------------------------------------------ column names
{
  const am = src('src/data/automap.ts');
  const roles = [
    ['X', 'X_NAMES'], ['Y', 'Y_NAMES'], ['Z', 'Z_NAMES'], ['Time', 'TIME_NAMES'], ['Person', 'PERSON_NAMES'],
    ['Session (match, round)', 'SESSION_NAMES'], ['Group (team)', 'TEAM_NAMES'], ['Yaw', 'YAW_NAMES'], ['Pitch', 'PITCH_NAMES'],
  ];
  let body = 'When a file is loaded, each role is given to the first column whose name matches one of these patterns (regular expressions, tried in order; `i` = any case). Every guess can be changed in [Column mapping](column-mapping.md), and a Parquet file can name its columns itself ([the `heat3d` hints](data-formats.md#the-heat3d-hints)).\n\n| Role | Name patterns |\n|---|---|\n';
  for (const [role, name] of roles) {
    const start = am.indexOf(`const ${name} = [`);
    if (start < 0) continue;
    const text = am.slice(start, am.indexOf('];', start));
    const pats = [...text.matchAll(/(\/(?:\\\/|[^/\n])+\/[a-z]*)/g)].map((m) => `\`${cell(m[1])}\``);
    if (/\.\.\.ELAPSED_NAMES/.test(text)) pats.push('and elapsed-time names (`elapsed`, `match_time` ...)');
    body += `| ${role} | ${pats.join(' ')} |\n`;
  }
  pages['ref-columns.md'] = page('Column names', 2, body);
}

// ------------------------------------------------------------ languages
{
  const lang = src('src/i18n/languages.ts');
  const list = [...lang.slice(lang.indexOf('export const LANGUAGES')).matchAll(/\{ code: '([\w-]+)', name: '([^']+)'/g)];
  let body = `The viewer speaks ${list.length} languages. It starts in the browser's language when it has it, and the language menu at the top of the sidebar changes it. More in [Languages](languages.md).\n\n| Code | Language |\n|---|---|\n`;
  for (const [, code, name] of list) body += `| \`${code}\` | ${name} |\n`;
  pages['ref-languages.md'] = page('Languages', 3, body);
}

// ------------------------------------------------------------ browser keys
{
  const bk = src('src/ui/browserKeys.ts');
  const set = (name) => [...bk.match(new RegExp(`${name} = (?:new Set\\()?\\[([^\\]]*)\\]`))[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
  const ctrl = set('SWALLOWED');
  const plain = set('SWALLOWED_PLAIN');
  const locked = set('LOCKED');
  const body = `So that a loaded session is not lost to a stray shortcut, the viewer keeps these keys from the browser.

| Keys | When | Effect |
|---|---|---|
| ${ctrl.map((k) => `\`Ctrl+${k.toUpperCase()}\``).join(' ')} (also with \`Cmd\`) | outside text boxes | the browser's action (print, save, open, reload, new window, close ...) does not happen |
| ${plain.map((k) => `\`${k}\``).join(' ')} | always | the browser's action (help, find, reload, address bar, caret browsing) does not happen |
| ${locked.map((k) => `\`${k.replace(/^Key/, '')}\``).join(' ')} | in full screen | locked for the viewer (Keyboard Lock API), so the browser does not act on them |
| closing or reloading the tab | with data or a level loaded | the browser asks first |

All the viewer's own keys: [Keyboard and mouse reference](keyboard-reference.md).`;
  pages['ref-browser-keys.md'] = page('Browser keys', 4, body);
}

// ------------------------------------------------------------ settings kept in the browser
{
  const MEANING = {
    'heat3d.language': 'the language picked',
    'heat3d.units': 'the units preset and single units',
    'heat3d.help': 'help mode on or off',
    'heat3d.far': 'figures at a distance, symbols, hit marks, aim lines',
    'heat3d.replay': 'replay labels, tactical display, 2D map, charts, head-up display, look, buildings, follow camera',
    'heat3d.speed': 'the playback speed',
    'heat3d.mirror': 'the axis mirroring',
    'heat3d.inspect': 'the pick card and camera readout',
    'heat3d.bookmarks.': 'bookmarks, per recording',
    '3dheat.volumes.': 'volumes, per dataset',
    '3dheat.objectives': 'objectives shown, layers, labels',
    'heat3d.carNames': 'car names in the race tab',
    'heat3d.ai': 'external AI: provider, address, model, options (not the key)',
    'heat3d.ai.key': 'the external AI key, only when *Remember the key* is ticked',
  };
  const found = new Map();
  const walk = (dir) => {
    for (const f of readdirSync(join(REPO, dir), { withFileTypes: true })) {
      const p = `${dir}/${f.name}`;
      if (f.isDirectory()) walk(p);
      else if (/\.(ts|tsx)$/.test(f.name) && !/\.test\.ts$/.test(f.name)) {
        const text = src(p);
        if (!/localStorage/.test(text)) continue;
        for (const m of text.matchAll(/['`]((?:heat3d|3dheat)\.[A-Za-z.]*)(?=['`$])/g)) if (!found.has(m[1])) found.set(m[1], p);
      }
    }
  };
  walk('src');
  let body = 'What the viewer keeps in your browser (`localStorage`) between visits. Nothing of it is sent anywhere. Clearing the site data in the browser removes it all.\n\n| Key | Holds | Code |\n|---|---|---|\n';
  for (const [key, file] of [...found].sort()) {
    if (key.endsWith('.') && !(key in MEANING)) continue;
    body += `| \`${key}${key.endsWith('.') ? '…' : ''}\` | ${MEANING[key] ?? ''} | \`${file}\` |\n`;
  }
  body += '\nHeat settings, filters and the view mode are not kept: they start fresh with each load.';
  pages['ref-settings-storage.md'] = page('Stored settings', 5, body);
}

// ------------------------------------------------------------ value tables
{
  let body = 'The price tables of [Value weighting](value-weighting.md). The game is recognised from names in the data; a converter\'s own value columns in the game\'s currency win over these.\n\n| Table | Currency | Defined in |\n|---|---|---|\n';
  for (const f of readdirSync(join(REPO, 'src/data/costs'))) {
    if (!f.endsWith('.ts') || f.endsWith('.test.ts')) continue;
    for (const m of src(`src/data/costs/${f}`).matchAll(/id: '([\w-]+)',\s*label: '([^']+)',\s*currency: '(\w+)'/g)) body += `| ${m[2]} | \`${m[3]}\` | \`src/data/costs/${f}\` |\n`;
  }
  pages['ref-value-tables.md'] = page('Value tables', 6, body);
}

// ------------------------------------------------------------ command-line tools
{
  const TOOLS = ['3dheat-pack.mjs', '3dheat-summarize.mjs', 'acmi-to-parquet.mjs', 'container.mjs', 'demo-data.mjs', 'docs-shots.mjs', 'docs-refs.mjs', 'smoke.mjs', 'check-visual.mjs', 'convert-media.mjs'];
  let body = 'The command-line tools in the viewer\'s `tools/` folder (Node.js, run from the repository root). The first paragraph of each tool\'s own description and its usage lines; run a tool without arguments for its full help where it has one. The data tools of the [related repositories](index.md#related-repositories) document their own commands.\n';
  for (const t of TOOLS) {
    if (!existsSync(join(REPO, 'tools', t))) continue;
    const text = src(`tools/${t}`);
    const block = text.match(/\/\*\*([\s\S]*?)\*\//)?.[1] ?? '';
    const lines = block.split('\n').map((l) => l.replace(/^\s*\* ?/, ''));
    const first = [];
    for (const l of lines.slice(lines[0].trim() ? 0 : 1)) {
      if (!l.trim()) break;
      first.push(l.trim());
    }
    const usage = lines.filter((l) => /^\s*(node tools\/|npm run )/.test(l)).map((l) => l.trim());
    body += `\n## \`${t}\`\n\n${first.join(' ')}\n`;
    if (usage.length) body += `\n\`\`\`\n${usage.join('\n')}\n\`\`\`\n`;
  }
  pages['ref-tools.md'] = page('Command-line tools', 7, body);
}

let changed = 0;
mkdirSync(OUT, { recursive: true });
for (const [name, text] of Object.entries(pages)) {
  const file = join(OUT, name);
  const old = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (old === text) continue;
  changed++;
  if (CHECK) console.log(`would change: ${name}`);
  else writeFileSync(file, text);
}
console.log(`${Object.keys(pages).length} reference pages, ${changed} ${CHECK ? 'out of date' : 'written'} (${LANG})`);
if (CHECK && changed) process.exit(1);
